"""
Build Muse with Nuitka: ``python build_exe.py``.

Nuitka compiles the code to C, then to a single native executable that embeds
the Python runtime. Needs a C compiler: Xcode Command Line Tools on macOS; on
Windows, Visual Studio Build Tools, or Nuitka downloads MinGW itself. Nuitka
does not cross-compile, so run this on each target OS.

Builds inside a dedicated ``.venv-build`` at the repo root, populated from
requirements-build.txt, so packages from the active conda env or venv aren't
bundled. The venv is based on the interpreter running this script, and the exe
embeds that interpreter's runtime. ``--current-env`` builds with the running
interpreter instead; it must already have requirements-build.txt installed.

Coqui TTS is compiled in from a checkout of it: ``--coqui-path=<dir>``, or
else ``coqui_tts_location`` from the user's config.json. Its dependencies come
from requirements.txt. The build supports Coqui as its only TTS provider.

The output, dist/Muse (macOS/Linux) or dist\\Muse.exe (Windows), is
smoke-tested with ``Muse --smoke-test``, which needs VLC installed on the build
machine. Other args are forwarded to Nuitka, e.g. ``--show-scons`` or
``--jobs=4``.

``--with-oqs`` adds quantum-safe (OQS) key encapsulation: it installs
liboqs-python, finds the liboqs shared library the build interpreter loads, and
bundles it. liboqs-python builds liboqs on first import if none is installed,
which needs git, CMake and a C compiler; or point OQS_INSTALL_PATH at an
existing install. Without the option the build has no OQS, and data encrypted
with OQS keys cannot be read by it.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import venv

REPO_ROOT = os.path.dirname(os.path.abspath(__file__))
VENV_DIR = os.path.join(REPO_ROOT, ".venv-build")
BUILD_DIR = os.path.join(REPO_ROOT, "build", "nuitka")
ICON_PNG = os.path.join("assets", "icon.png")
ICON_ICO = os.path.join(BUILD_DIR, "muse_icon.ico")
EXE_BASE_NAME = "Muse"
ENTRY = "app_qt.py"

# Shipped files, at the same relative paths utils.app_paths.resource_path()
# resolves them under.
DATA_DIRS = ("locale", "prompts", os.path.join("lib", "sounds"))
DATA_FILES = (
    os.path.join("tts", "dictionary_en.txt"),
    os.path.join("extensions", "library_ext_q_dict.enc"),
    os.path.join("library_data", "data", "blacklist_default.enc"),
    os.path.join("library_data", "data", "config_example.json"),
    os.path.join("library_data", "data", "artists_example.json"),
    os.path.join("library_data", "data", "composers_example.json"),
    os.path.join("library_data", "data", "forms_example.json"),
    os.path.join("library_data", "data", "genres_example.json"),
    os.path.join("library_data", "data", "instruments_example.json"),
)
ASSETS_DIR = "assets"
# Generated by the app (spinning record clips live in the user cache dir).
ASSETS_EXCLUDES = ("spinning_record_videos",)
# TTS providers the build leaves out; it contains Coqui only.
EXCLUDED_TTS_PACKAGES = ("kokoro_onnx", "f5_tts", "amphion", "piper", "zonos")
TRANSFORMERS_PROBED_DISTRIBUTIONS = (
    "jieba", "jinja2", "librosa", "pandas", "psutil", "pygments", "safetensors",
    "scipy", "soundfile", "spacy", "tokenizers", "torch", "torchaudio",
)
# Same source as requirements-optional.txt; not on PyPI.
LIBOQS_PYTHON = "git+https://github.com/open-quantum-safe/liboqs-python.git"
# Prints the path of the liboqs shared library liboqs-python loaded.
_LIBOQS_PROBE = (
    "import oqs.oqs as m\n"
    "lib = m.native() if hasattr(m, 'native') else m._liboqs\n"
    "print(lib._name)\n"
)


def _venv_python(venv_dir: str) -> str:
    if sys.platform == "win32":
        return os.path.join(venv_dir, "Scripts", "python.exe")
    return os.path.join(venv_dir, "bin", "python")


def _exe_name(base: str) -> str:
    return f"{base}.exe" if sys.platform == "win32" else base


def _ensure_build_venv(extra_packages=()) -> str:
    python = _venv_python(VENV_DIR)
    if not os.path.exists(python):
        print(f"Creating build venv at {VENV_DIR}")
        venv.create(VENV_DIR, with_pip=True)
    subprocess.run(
        [python, "-m", "pip", "install", "-q", "-r", os.path.join(REPO_ROOT, "requirements-build.txt"),
         *extra_packages],
        check=True,
    )
    return python


def _user_config_path() -> str:
    """config.json as utils/app_paths.py locates it, resolved without importing the app."""
    configs_dir = os.environ.get("MUSE_CONFIGS_DIR")
    if not configs_dir:
        app_data_dir = os.environ.get("MUSE_APP_DATA_DIR")
        if not app_data_dir:
            if sys.platform == "win32":
                base = os.environ.get("APPDATA") or os.path.join(os.path.expanduser("~"), "AppData", "Roaming")
            else:
                base = os.path.join(os.path.expanduser("~"), ".local", "share")
            app_data_dir = os.path.join(base, "muse")
        configs_dir = os.path.join(app_data_dir, "configs")
    path = os.path.join(configs_dir, "config.json")
    if os.path.isfile(path):
        return path
    # Not migrated yet: the app moves it on its next start.
    return os.path.join(REPO_ROOT, "configs", "config.json")


def _coqui_location(cli_value) -> str:
    """The Coqui TTS checkout: the command line, else coqui_tts_location from config.json."""
    location = cli_value
    source = "--coqui-path"
    if not location:
        config_path = _user_config_path()
        source = f"coqui_tts_location in {config_path}"
        try:
            with open(config_path, "r", encoding="utf-8") as f:
                location = json.load(f).get("coqui_tts_location") or ""
        except (OSError, ValueError) as e:
            print(f"Could not read {config_path}: {e}")
            location = ""
        location = location.strip().replace("{HOME}", os.path.expanduser("~"))
    location = os.path.abspath(os.path.expanduser(location)) if location else ""
    if not location or not os.path.isfile(os.path.join(location, "TTS", "__init__.py")):
        sys.exit(
            f"Coqui TTS checkout not found (from {source}: {location or 'not set'}).\n"
            "Pass --coqui-path=<dir> with the directory containing the TTS package, "
            "or set coqui_tts_location in config.json."
        )
    print(f"Coqui TTS from {location}")
    return location


def _assets_files() -> list:
    """Every file under assets/ except generated ones, as repo-relative paths."""
    files = []
    root = os.path.join(REPO_ROOT, ASSETS_DIR)
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in ASSETS_EXCLUDES]
        for name in filenames:
            files.append(os.path.relpath(os.path.join(dirpath, name), REPO_ROOT))
    return sorted(files)


def _write_windows_icon(python: str) -> None:
    """Render the PNG app icon to the .ico Nuitka needs, with the build venv's Qt."""
    os.makedirs(BUILD_DIR, exist_ok=True)
    script = (
        "import sys\n"
        "from PySide6.QtCore import Qt\n"
        "from PySide6.QtGui import QGuiApplication, QImage\n"
        "app = QGuiApplication(sys.argv[:1])\n"
        "image = QImage(sys.argv[1]).scaled(256, 256, Qt.KeepAspectRatio, Qt.SmoothTransformation)\n"
        "sys.exit(0 if not image.isNull() and image.save(sys.argv[2], 'ICO') else 1)\n"
    )
    env = dict(os.environ, QT_QPA_PLATFORM="offscreen")
    subprocess.run([python, "-c", script, os.path.join(REPO_ROOT, ICON_PNG), ICON_ICO], env=env, check=True)


def _nuitka_args(exe_name: str) -> list:
    # The onefile exe unpacks its runtime to this folder. A fixed path (no
    # {PID}/{TIME}) makes Nuitka keep it between runs, so only the first run
    # pays the unpacking cost. The build id gives each build its own folder so
    # a rebuilt exe never reuses a previous build's files; old folders under
    # unpacked/ are safe to delete. It sits in the app data dir
    # (utils/app_paths.py), spelled from {HOME} because Nuitka has no variable
    # for %APPDATA%; nothing the app writes goes under unpacked/.
    build_id = time.strftime("%Y%m%d-%H%M%S")
    app_data_spec = "{HOME}/AppData/Roaming/muse" if sys.platform == "win32" else "{HOME}/.local/share/muse"
    args = [
        "--onefile",
        f"--onefile-tempdir-spec={app_data_spec}/unpacked/muse-{build_id}",
        f"--output-dir={BUILD_DIR}",
        f"--output-filename={exe_name}",
        # Lets Nuitka fetch build helpers (e.g. MinGW on Windows) without prompting.
        "--assume-yes-for-downloads",
        "--enable-plugin=pyside6",
        # keyring finds its backends, including the OS one, through package
        # metadata entry points; without it encrypted saves cannot work.
        "--include-distribution-metadata=keyring",
        # Coqui TTS is imported from the checkout put on PYTHONPATH for this
        # run. It reads its model list and configs from package data; trainer
        # reads its VERSION file at import, gruut loads its language packs,
        # and the Chinese and Korean text front ends their dictionaries, the
        # same way.
        "--include-package=TTS",
        "--include-package-data=TTS",
        "--include-package-data=trainer",
        "--include-package=gruut_lang_en",
        "--include-package-data=gruut",
        "--include-package-data=gruut_ipa",
        "--include-package-data=gruut_lang_en",
        "--include-package-data=jamo",
        "--include-package-data=jieba",
        "--include-package-data=pypinyin",
        # transformers reads the installed version of every optional package
        # it finds importable; for a bundled package without its metadata,
        # the build exits at that lookup. These are the packages it checks
        # that are in requirements.txt (transformers 4.45).
        *[f"--include-distribution-metadata={p}" for p in TRANSFORMERS_PROBED_DISTRIBUTIONS],
        # The library extender imports a module whose name it decrypts at
        # runtime, which import following cannot see.
        "--include-package=googleapiclient",
        "--include-package-data=googleapiclient",
        # numba and TorchScript compile Python functions from their bytecode,
        # which compiled functions do not have; both fall back to plain Python.
        "--module-parameter=numba-disable-jit=yes",
        "--module-parameter=torch-disable-jit=yes",
        "--nofollow-import-to=pytest",
        "--nofollow-import-to=_pytest",
    ]
    args += [f"--nofollow-import-to={p}" for p in EXCLUDED_TTS_PACKAGES]
    args += [f"--include-data-dir={d}={d}" for d in DATA_DIRS]
    args += [f"--include-data-files={f}={f}" for f in (*DATA_FILES, *_assets_files())]
    if sys.platform == "win32":
        args.append(f"--windows-icon-from-ico={ICON_ICO}")
        # No console window when started from Explorer; when started from a
        # terminal, output (e.g. the smoke test's) goes to that terminal.
        args.append("--windows-console-mode=attach")
    return args


def _oqs_args(python: str, with_oqs: bool) -> list:
    if not with_oqs:
        # Keep liboqs-python out even if the build environment has it: without
        # its shared library it would try to build liboqs at the app's startup.
        return ["--nofollow-import-to=oqs"]
    probe = subprocess.run([python, "-c", _LIBOQS_PROBE], capture_output=True, text=True)
    library = probe.stdout.strip().splitlines()[-1] if probe.stdout.strip() else ""
    if probe.returncode != 0 or not os.path.isabs(library) or not os.path.isfile(library):
        sys.exit(
            "--with-oqs: could not locate the liboqs shared library through liboqs-python.\n"
            f"{probe.stdout}{probe.stderr}\n"
            "Install liboqs (or let liboqs-python build it: needs git, CMake and a C "
            "compiler) or set OQS_INSTALL_PATH to an existing install, then rebuild."
        )
    # The layout liboqs-python searches under OQS_INSTALL_PATH, which
    # utils/encryptor.py points at this folder in the build.
    lib_dir = "bin" if sys.platform == "win32" else "lib"
    print(f"Bundling liboqs: {library}")
    return [
        "--include-package=oqs",
        "--include-distribution-metadata=liboqs-python",
        f"--include-data-files={library}=liboqs/{lib_dir}/{os.path.basename(library)}",
    ]


def _smoke_test(exe_path: str, with_oqs: bool) -> None:
    # Run from outside the repo so a passing test can't depend on the checkout,
    # with all app data (logs included) and the key store in a scratch
    # directory so the user's are untouched.
    with tempfile.TemporaryDirectory(prefix="muse-smoke-") as scratch:
        env = dict(os.environ)
        env["QT_QPA_PLATFORM"] = "offscreen"
        env["MUSE_APP_DATA_DIR"] = scratch
        env["MUSE_CACHE_DIR"] = os.path.join(scratch, "cache")
        env.pop("MUSE_CONFIGS_DIR", None)
        env["MUSE_SKIP_VLC_PLUGIN_CACHE_FIX"] = "1"
        result = subprocess.run(
            [exe_path, "--smoke-test", *(["--expect-oqs"] if with_oqs else [])],
            cwd=os.path.expanduser("~"), env=env,
            capture_output=True, text=True, errors="replace",
        )
    sys.stdout.write(result.stdout + result.stderr)
    if result.returncode != 0:
        sys.exit(f"Smoke test failed: `{exe_path} --smoke-test` exited {result.returncode}")


def _pop_option(args: list, name: str):
    """Remove ``name=value`` from *args* and return the value, or None."""
    for arg in list(args):
        if arg.startswith(name + "="):
            args.remove(arg)
            return arg.split("=", 1)[1]
    return None


if __name__ == "__main__":
    args = sys.argv[1:]
    with_oqs = "--with-oqs" in args
    if with_oqs:
        args.remove("--with-oqs")
    coqui_location = _coqui_location(_pop_option(args, "--coqui-path"))
    extra_packages = (LIBOQS_PYTHON,) if with_oqs else ()
    exe_name = _exe_name(EXE_BASE_NAME)
    exe_path = os.path.join(REPO_ROOT, "dist", exe_name)

    if "--current-env" in args:
        args.remove("--current-env")
        python = sys.executable
    else:
        python = _ensure_build_venv(extra_packages)

    if sys.platform == "win32":
        _write_windows_icon(python)
    nuitka_args = [
        *_nuitka_args(exe_name), *_oqs_args(python, with_oqs),
        *args, os.path.join(REPO_ROOT, ENTRY),
    ]
    nuitka_env = dict(os.environ)
    nuitka_env["PYTHONPATH"] = os.pathsep.join(
        p for p in (coqui_location, nuitka_env.get("PYTHONPATH")) if p
    )
    subprocess.run([python, "-m", "nuitka", *nuitka_args], cwd=REPO_ROOT, env=nuitka_env, check=True)
    os.makedirs(os.path.dirname(exe_path), exist_ok=True)
    shutil.copy2(os.path.join(BUILD_DIR, exe_name), exe_path)
    _smoke_test(exe_path, with_oqs)
    print(f"Built {exe_path}")
